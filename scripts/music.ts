import { duration } from "../src/production";
import { FPS } from "../src/config";
import { directory, hash, load, root, save } from "./io";
import { resolve } from "node:path";

export async function music() {
  const production = await load();
  const seconds = Math.ceil(duration(production) / FPS + 3);
  const rate = 44100;
  const count = rate * seconds;
  const buffer = Buffer.alloc(44 + count * 2);
  buffer.write("RIFF", 0);
  buffer.writeUInt32LE(36 + count * 2, 4);
  buffer.write("WAVEfmt ", 8);
  buffer.writeUInt32LE(16, 16);
  buffer.writeUInt16LE(1, 20);
  buffer.writeUInt16LE(1, 22);
  buffer.writeUInt32LE(rate, 24);
  buffer.writeUInt32LE(rate * 2, 28);
  buffer.writeUInt16LE(2, 32);
  buffer.writeUInt16LE(16, 34);
  buffer.write("data", 36);
  buffer.writeUInt32LE(count * 2, 40);
  const chords = [
    [146.83, 174.61, 220],
    [130.81, 164.81, 196],
    [116.54, 146.83, 174.61],
    [130.81, 174.61, 220],
  ];
  for (let index = 0; index < count; index++) {
    const t = index / rate;
    const beat = (t * 96) / 60;
    const chord = chords[Math.floor(beat / 8) % chords.length];
    const p = beat % 1;
    const chordEnvelope = Math.min(1, (beat % 8) * 2, (8 - (beat % 8)) * 2);
    const pad =
      chord.reduce((sum, hz) => sum + Math.sin(2 * Math.PI * hz * t), 0) *
      0.045 *
      chordEnvelope;
    const bass =
      Math.sin(((2 * Math.PI * chord[0]) / 2) * t) * Math.exp(-p * 7) * 0.11;
    const melody =
      Math.sin(2 * Math.PI * chord[Math.floor(beat * 2) % 3] * 2 * t) *
      Math.exp(-((beat * 2) % 1) * 10) *
      0.06;
    const tick =
      Math.sin(index * 12.9898) *
      Math.sin(index * 78.233) *
      Math.exp(-p * 90) *
      0.022;
    const fade = Math.min(1, t / 2, (seconds - t) / 3);
    buffer.writeInt16LE(
      Math.round((pad + bass + melody + tick) * fade * 32767),
      44 + index * 2,
    );
  }
  await directory("public/media/music");
  const file = "media/music/stackanvil-original.wav";
  await Bun.write(resolve(root, "public", file), buffer);
  production.music = {
    file,
    sha256: await hash(resolve(root, "public", file)),
    duration: seconds,
    license: "Original score generated by StackAnvil/video; CC0-1.0",
  };
  await save(production);
  console.log(`Original music: ${seconds}s`);
}
