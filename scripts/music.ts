import { resolve } from "node:path";

import { Effect, Option, Schema } from "effect";

import { FPS } from "../src/config";
import { duration } from "../src/production";
import { required } from "../src/required";
import { elevenLabs, setting } from "./elevenlabs";
import {
  decode,
  directory,
  exists,
  fail,
  hash,
  load,
  mediaDuration,
  readJson,
  root,
  run,
  save,
  write,
} from "./io";

export const music = Effect.fnUntraced(function* (requestedMode?: string) {
  const mode =
    requestedMode ?? (yield* setting("STACKANVIL_MUSIC", "original"));
  if (mode === "elevenlabs") return yield* generatedMusic();
  if (mode !== "original")
    return yield* fail("Choose original or elevenlabs music");
  const production = yield* load();
  const seconds = Math.ceil(
    Math.max(duration(production), duration(production, "vertical")) / FPS + 3,
  );
  const rate = 44100;
  const count = rate * seconds;
  const buffer = Buffer.alloc(44 + count * 2);
  buffer.write("RIFF", 0);
  buffer.writeUInt32LE(36 + count * 2, 4);
  buffer.write("WAVEfmt ", 8);
  buffer.writeUInt32LE(16, 16);
  buffer.writeUInt16LE(1, 20);
  buffer.writeUInt16LE(1, 22);
  buffer.writeUInt32LE(rate, 24);
  buffer.writeUInt32LE(rate * 2, 28);
  buffer.writeUInt16LE(2, 32);
  buffer.writeUInt16LE(16, 34);
  buffer.write("data", 36);
  buffer.writeUInt32LE(count * 2, 40);
  const chords: [number, number, number][] = [
    [146.83, 174.61, 220],
    [130.81, 164.81, 196],
    [116.54, 146.83, 174.61],
    [130.81, 174.61, 220],
  ];
  for (let index = 0; index < count; index++) {
    const t = index / rate;
    const beat = (t * 96) / 60;
    const chord = required(
      chords[Math.floor(beat / 8) % chords.length],
      "chord",
    );
    const p = beat % 1;
    const chordEnvelope = Math.min(1, (beat % 8) * 2, (8 - (beat % 8)) * 2);
    const pad =
      chord.reduce((sum, hz) => sum + Math.sin(2 * Math.PI * hz * t), 0) *
      0.045 *
      chordEnvelope;
    const bass =
      Math.sin(((2 * Math.PI * chord[0]) / 2) * t) * Math.exp(-p * 7) * 0.11;
    const melody =
      Math.sin(
        2 * Math.PI * required(chord[Math.floor(beat * 2) % 3], "note") * 2 * t,
      ) *
      Math.exp(-((beat * 2) % 1) * 10) *
      0.06;
    const tick =
      Math.sin(index * 12.9898) *
      Math.sin(index * 78.233) *
      Math.exp(-p * 90) *
      0.022;
    const fade = Math.min(1, t / 2, (seconds - t) / 3);
    buffer.writeInt16LE(
      Math.round((pad + bass + melody + tick) * fade * 32767),
      44 + index * 2,
    );
  }
  yield* directory("public/media/music");
  const file = "media/music/stackanvil-original.wav";
  yield* write(resolve(root, "public", file), buffer);
  production.music = {
    file,
    sha256: yield* hash(resolve(root, "public", file)),
    duration: seconds,
    license: "Original score generated by StackAnvil/video; CC0-1.0",
  };
  yield* save(production);
  process.stdout.write(`Original music: ${seconds}s\n`);
  return undefined;
});

const MusicCache = Schema.Struct({ signature: Schema.String });

const generatedMusic = Effect.fnUntraced(function* () {
  const production = yield* load();
  const seconds = Math.ceil(
    Math.max(duration(production), duration(production, "vertical")) / FPS + 3,
  );
  const prompt =
    "An original, understated warm electronic instrumental for a calm Minecraft technology walkthrough. Soft Rhodes and felt keys, muted synth bass, airy pads and light brushed percussion. Around 86 BPM with a relaxed humanized groove and occasional small fills. Slowly evolving harmony and instrumentation, generous space in the midrange for spoken narration. Gentle forward motion for the first three minutes, quieter and more spacious textures during the technical explanation after three and a half minutes, a warm restrained resolution in the final thirty seconds. No dramatic drops, no constant repeating arpeggio, no sound effects or jingles. No voices, singing, chants or spoken words.";
  const request = {
    model_id: "music_v2_5",
    prompt,
    music_length_ms: seconds * 1000,
    force_instrumental: true,
  };
  yield* directory(".cache/music");
  yield* directory("public/media/music");
  const metadata = resolve(root, ".cache/music/elevenlabs.json");
  const cache = resolve(root, ".cache/music/elevenlabs.mp3");
  const signature = JSON.stringify(request);
  const cached =
    (yield* exists(cache)) && (yield* exists(metadata))
      ? yield* readJson(metadata).pipe(
          Effect.flatMap(decode(MusicCache, "Music cache")),
          Effect.option,
        )
      : Option.none();
  if (Option.isNone(cached) || cached.value.signature !== signature) {
    const response = yield* elevenLabs({
      path: "music?output_format=auto",
      body: signature,
      purpose: "music",
      timeoutSeconds: 600,
      rejected: (status) => `Eleven Music returned ${status}`,
    });
    yield* write(cache, response.bytes);
    yield* write(
      metadata,
      JSON.stringify({ signature, songId: response.headers.get("song-id") }),
    );
  }
  const file = "media/music/stackanvil-elevenlabs.wav";
  const path = resolve(root, "public", file);
  const sourceDuration = yield* mediaDuration(cache);
  const crossfade = 4;
  const repeat = seconds - sourceDuration + 2 * crossfade;
  const pivot = sourceDuration * 0.55;
  if (sourceDuration < seconds) {
    if (repeat >= pivot)
      return yield* fail(
        "Generated music is too short for a clean phrase repeat",
      );
    yield* run([
      "ffmpeg",
      "-nostdin",
      "-y",
      "-v",
      "error",
      "-i",
      cache,
      "-filter_complex",
      `[0:a]asplit=3[a][b][c];[a]atrim=end=${pivot},asetpts=PTS-STARTPTS[first];[b]atrim=start=${pivot - repeat}:end=${pivot},asetpts=PTS-STARTPTS[phrase];[c]atrim=start=${pivot},asetpts=PTS-STARTPTS[last];[first][phrase]acrossfade=d=${crossfade}:c1=qsin:c2=qsin[extended];[extended][last]acrossfade=d=${crossfade}:c1=qsin:c2=qsin,atrim=duration=${seconds}[music]`,
      "-map",
      "[music]",
      "-ar",
      "48000",
      "-c:a",
      "pcm_s16le",
      path,
    ]);
    process.stdout.write(
      `Repeated one middle phrase with crossfades: ${sourceDuration.toFixed(2)}s source → ${seconds}s edit\n`,
    );
  } else {
    yield* run([
      "ffmpeg",
      "-nostdin",
      "-y",
      "-v",
      "error",
      "-i",
      cache,
      "-t",
      String(seconds),
      "-ar",
      "48000",
      "-c:a",
      "pcm_s16le",
      path,
    ]);
  }
  production.music = {
    file,
    sha256: yield* hash(path),
    duration: yield* mediaDuration(path),
    license: "Generated with Eleven Music v2.5; ElevenLabs music terms apply",
  };
  yield* save(production);
  process.stdout.write(`Eleven Music v2.5: ${production.music.duration}s\n`);
  return undefined;
});
